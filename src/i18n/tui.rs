/// Interface text for one language. Languages without a dedicated table
/// derive page names and common key labels from their existing catalog and
/// fall back to English for the remaining page copy.
pub fn text(lang: Lang) -> &'static TuiText {
    match lang {
        Lang::En => &EN,
        Lang::Es => &ES,
        _ => derived(lang),
    }
}

fn derived(lang: Lang) -> &'static TuiText {
    use std::sync::OnceLock;
    static CACHE: [OnceLock<TuiText>; 11] = [const { OnceLock::new() }; 11];
    let index = Lang::ALL.iter().position(|&l| l == lang).unwrap_or(0);
    CACHE[index].get_or_init(|| {
        let l = super::txt(lang);
        // The historical footers already translate the common key labels;
        // look them up by key so a catalog's ordering cannot misplace them.
        let footer = |row: usize, key: &str, fallback: &'static str| {
            l.footer[row]
                .iter()
                .find(|(k, _)| *k == key)
                .map_or(fallback, |(_, label)| *label)
        };
        let browser = |row: usize, key: &str, fallback: &'static str| {
            l.features_footer[row]
                .iter()
                .find(|(k, _)| *k == key)
                .map_or(fallback, |(_, label)| *label)
        };
        // Historical catalog arrays: navigation = Home, Audio, Devices,
        // Settings, Diagnostics, Research; page_labels[3] = Multipoint.
        let n = l.navigation;
        TuiText {
            pages: [
                n[0],
                n[3],
                l.features_title.trim(),
                n[2],
                l.page_labels[3],
                n[1],
                n[4],
                n[5],
            ],
            h_address: footer(0, "a", EN.h_address),
            h_devices: footer(0, "p", EN.h_devices),
            h_model: footer(0, "m", EN.h_model),
            h_connect: footer(0, "c", EN.h_connect),
            h_refresh: footer(0, "r", EN.h_refresh),
            h_disconnect: footer(0, "d", EN.h_disconnect),
            h_apply: footer(1, "Enter", EN.h_apply),
            h_review: footer(1, "Enter", EN.h_review),
            h_confirm: footer(1, "y", EN.h_confirm),
            h_back: footer(1, "Esc", EN.h_back),
            h_discard: footer(1, "Esc", EN.h_discard),
            h_log: footer(2, "l", EN.h_log),
            h_help: footer(2, "?", EN.h_help),
            h_language: footer(2, "L", EN.h_language),
            h_options: footer(2, "s", EN.h_options),
            h_quit: footer(2, "q", EN.h_quit),
            h_move: browser(0, "Up", EN.h_move),
            h_tabs: browser(0, "Tab", EN.h_tabs),
            h_open: browser(0, "Enter", EN.h_open),
            h_select: browser(0, "Enter", EN.h_select),
            h_search: browser(1, "letters", EN.h_search),
            h_unset: browser(1, "Backspace", EN.h_unset),
            h_clear: browser(1, "Ctrl+U", EN.h_clear),
            h_cancel: browser(2, "Esc", EN.h_cancel),
            h_done: browser(2, "Esc", EN.h_done),
            ..EN
        }
    })
}
